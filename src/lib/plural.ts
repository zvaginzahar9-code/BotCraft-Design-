/**
 * Русское склонение существительного при числительном.
 *
 * Счётчики на странице приходят из базы, поэтому «72 моделей» вместо «72
 * модели» — не опечатка в тексте, а отсутствующее правило. Форма выбирается по
 * последним разрядам числа: 1, 21, 31 берут единственное, 2-4 и 22-24 —
 * родительный единственного, всё остальное — родительный множественного.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(n) % 100;
  if (abs >= 11 && abs <= 14) return many;
  const last = abs % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}
